#!/usr/bin/env node
// Fetches the OpenCode desktop theme set (37 themes) and transpiles each
// theme's light/dark CSS-variable maps into a TS registry
// (src/lib/theme/themes.ts). The App applies the variables to :root the same
// way OpenCode does (palette < v2Overrides < overrides).
//
// Usage: node scripts/fetch-themes.mjs

import { writeFileSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const THEME_NAMES = [
  "amoled", "aura", "ayu", "carbonfox", "catppuccin-frappe", "catppuccin-macchiato",
  "catppuccin", "cobalt2", "cursor", "dracula", "everforest", "flexoki", "github",
  "gruvbox", "kanagawa", "lucent-orng", "material", "matrix", "mercury", "monokai",
  "nightowl", "nord", "oc-2", "one-dark", "onedarkpro", "opencode", "orng",
  "osaka-jade", "palenight", "rosepine", "shadesofpurple", "solarized", "synthwave84",
  "tokyonight", "vercel", "vesper", "zenburn",
]

const BASE =
  "https://raw.githubusercontent.com/anomalyco/opencode/dev/packages/ui/src/theme/themes"

/** Merge palette + v2Overrides + overrides (later wins) into one var map. */
function flattenSection(section) {
  const out = {}
  if (!section) return out
  for (const src of [section.palette, section.v2Overrides, section.overrides]) {
    if (src && typeof src === "object") Object.assign(out, src)
  }
  return out
}

async function fetchTheme(name) {
  const res = await fetch(`${BASE}/${name}.json`)
  if (!res.ok) throw new Error(`fetch ${name}.json -> ${res.status}`)
  const raw = await res.json()
  return {
    id: raw.id ?? name,
    name: raw.name ?? name,
    light: flattenSection(raw.light),
    dark: flattenSection(raw.dark),
  }
}

const themes = await Promise.all(THEME_NAMES.map(fetchTheme))
// oc-2 is OpenCode's default; keep it first so the picker defaults to it.
themes.sort((a, b) => (a.id === "oc-2" ? -1 : b.id === "oc-2" ? 1 : a.name.localeCompare(b.name)))

const lines = [
  "// Generated by scripts/fetch-themes.mjs — do not edit by hand.",
  "// Source: OpenCode desktop theme set (packages/ui/src/theme/themes).",
  "export interface ThemeDef {",
  "  id: string",
  "  name: string",
  "  light: Record<string, string>",
  "  dark: Record<string, string>",
  "}",
  "",
  `export const THEMES: ThemeDef[] = ${JSON.stringify(themes, null, 2)}`,
  "",
  'export const DEFAULT_THEME_ID = "oc-2"',
  "",
]
writeFileSync(
  join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "theme", "themes.ts"),
  lines.join("\n"),
)
console.log(`[fetch-themes] wrote ${themes.length} themes to src/lib/theme/themes.ts`)
